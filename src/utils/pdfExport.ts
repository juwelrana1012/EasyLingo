import { jsPDF } from 'jspdf';

export interface PdfWordItem {
  word: string;
  phonetic: string;
  partOfSpeech: string;
  meaning: string;
  exampleEn: string;
  exampleTranslated: string;
}

function wrapLines(
  ctx: CanvasRenderingContext2D,
  text: string,
  maxWidth: number
): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let current = '';

  for (const word of words) {
    const test = current ? `${current} ${word}` : word;
    if (ctx.measureText(test).width > maxWidth && current) {
      lines.push(current);
      current = word;
    } else {
      current = test;
    }
  }
  if (current) lines.push(current);
  return lines.length > 0 ? lines : [''];
}

/**
 * Generates a real multi-page PDF document with native browser HarfBuzz text shaping
 * so Bengali, Arabic, Hindi, Urdu, Japanese, and Latin scripts render crisply without missing glyphs.
 */
export function downloadVocabularyPdf(params: {
  topic: string;
  languageLabel: string;
  items: PdfWordItem[];
}) {
  const { topic, languageLabel, items } = params;
  if (items.length === 0) return;

  // A4 proportions at crisp 2x resolution: 1240 x 1754 px
  const PAGE_W = 1240;
  const PAGE_H = 1754;
  const MARGIN = 72;
  const CONTENT_W = PAGE_W - MARGIN * 2;

  const pdf = new jsPDF({
    orientation: 'portrait',
    unit: 'px',
    format: [PAGE_W / 2, PAGE_H / 2],
    compress: true,
  });

  const canvas = document.createElement('canvas');
  canvas.width = PAGE_W;
  canvas.height = PAGE_H;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  const FONT_SANS = '"Plus Jakarta Sans", "Hind Siliguri", "Noto Sans Bengali", system-ui, sans-serif';

  let pageNumber = 1;
  let y = MARGIN;

  const drawHeader = (isFirstPage: boolean) => {
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, PAGE_W, PAGE_H);

    // Top accent bar
    ctx.fillStyle = '#2563EB';
    ctx.fillRect(0, 0, PAGE_W, 14);

    if (isFirstPage) {
      ctx.fillStyle = '#2563EB';
      ctx.font = `700 22px ${FONT_SANS}`;
      ctx.fillText('LingoBangla — Vocabulary & Sentence Book', MARGIN, MARGIN + 26);

      ctx.fillStyle = '#111827';
      ctx.font = `800 36px ${FONT_SANS}`;
      ctx.fillText(`Topic: ${topic}`, MARGIN, MARGIN + 72);

      ctx.fillStyle = '#64748B';
      ctx.font = `500 20px ${FONT_SANS}`;
      ctx.fillText(
        `${items.length} Words · Meanings (${languageLabel}) & Example Sentences · ${new Date().toLocaleDateString()}`,
        MARGIN,
        MARGIN + 108
      );

      ctx.strokeStyle = '#E5E7EB';
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.moveTo(MARGIN, MARGIN + 130);
      ctx.lineTo(PAGE_W - MARGIN, MARGIN + 130);
      ctx.stroke();

      y = MARGIN + 158;
    } else {
      ctx.fillStyle = '#64748B';
      ctx.font = `600 18px ${FONT_SANS}`;
      ctx.fillText(`LingoBangla · ${topic} (${languageLabel})`, MARGIN, MARGIN + 18);

      ctx.strokeStyle = '#E5E7EB';
      ctx.lineWidth = 1.5;
      ctx.beginPath();
      ctx.moveTo(MARGIN, MARGIN + 34);
      ctx.lineTo(PAGE_W - MARGIN, MARGIN + 34);
      ctx.stroke();

      y = MARGIN + 60;
    }
  };

  const drawFooter = (pageNum: number) => {
    ctx.strokeStyle = '#E5E7EB';
    ctx.lineWidth = 1.5;
    ctx.beginPath();
    ctx.moveTo(MARGIN, PAGE_H - 64);
    ctx.lineTo(PAGE_W - MARGIN, PAGE_H - 64);
    ctx.stroke();

    ctx.fillStyle = '#64748B';
    ctx.font = `500 18px ${FONT_SANS}`;
    ctx.fillText('Generated by LingoBangla (Learn • Translate • Grow)', MARGIN, PAGE_H - 34);
    const pageStr = `Page ${pageNum}`;
    const w = ctx.measureText(pageStr).width;
    ctx.fillText(pageStr, PAGE_W - MARGIN - w, PAGE_H - 34);
  };

  drawHeader(true);

  items.forEach((item, index) => {
    ctx.font = `500 20px ${FONT_SANS}`;
    const meaningLines = wrapLines(ctx, `Meaning: ${item.meaning}`, CONTENT_W - 36);
    const exEnLines = wrapLines(ctx, `Example: ${item.exampleEn}`, CONTENT_W - 36);
    const exTrLines = wrapLines(ctx, `Translation: ${item.exampleTranslated}`, CONTENT_W - 36);

    const cardHeight =
      52 +
      meaningLines.length * 28 +
      exEnLines.length * 28 +
      exTrLines.length * 28 +
      26;

    if (y + cardHeight > PAGE_H - 86) {
      drawFooter(pageNumber);
      const imgData = canvas.toDataURL('image/jpeg', 0.92);
      if (pageNumber > 1) pdf.addPage();
      pdf.addImage(imgData, 'JPEG', 0, 0, PAGE_W / 2, PAGE_H / 2);
      pageNumber += 1;
      drawHeader(false);
    }

    // Card container
    ctx.fillStyle = index % 2 === 0 ? '#F8FAFC' : '#FFFFFF';
    ctx.strokeStyle = '#E5E7EB';
    ctx.lineWidth = 1.5;
    ctx.beginPath();
    ctx.roundRect(MARGIN, y, CONTENT_W, cardHeight, 12);
    ctx.fill();
    ctx.stroke();

    let cursorY = y + 34;

    // Word + POS + Phonetic
    ctx.fillStyle = '#2563EB';
    ctx.font = `700 23px ${FONT_SANS}`;
    const titleStr = `${index + 1}. ${item.word}`;
    ctx.fillText(titleStr, MARGIN + 18, cursorY);

    const titleWidth = ctx.measureText(titleStr).width;
    ctx.fillStyle = '#64748B';
    ctx.font = `500 18px ${FONT_SANS}`;
    ctx.fillText(`  ${item.phonetic}  ·  ${item.partOfSpeech}`, MARGIN + 18 + titleWidth, cursorY);

    cursorY += 32;

    // Meaning lines
    ctx.fillStyle = '#111827';
    ctx.font = `700 20px ${FONT_SANS}`;
    for (const line of meaningLines) {
      ctx.fillText(line, MARGIN + 18, cursorY);
      cursorY += 28;
    }

    // Example EN
    ctx.fillStyle = '#1E293B';
    ctx.font = `500 19px ${FONT_SANS}`;
    for (const line of exEnLines) {
      ctx.fillText(line, MARGIN + 18, cursorY);
      cursorY += 28;
    }

    // Example Translated
    ctx.fillStyle = '#475569';
    ctx.font = `500 19px ${FONT_SANS}`;
    for (const line of exTrLines) {
      ctx.fillText(line, MARGIN + 18, cursorY);
      cursorY += 28;
    }

    y += cardHeight + 14;
  });

  drawFooter(pageNumber);
  const finalImg = canvas.toDataURL('image/jpeg', 0.92);
  if (pageNumber > 1) pdf.addPage();
  pdf.addImage(finalImg, 'JPEG', 0, 0, PAGE_W / 2, PAGE_H / 2);

  const safeTopic = topic
    .toLowerCase()
    .replace(/[^a-z0-9\u0980-\u09FF]+/gi, '-')
    .replace(/(^-|-$)/g, '') || 'vocabulary';

  pdf.save(`LingoBangla-${safeTopic}-${items.length}-words.pdf`);
}
