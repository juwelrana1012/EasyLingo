export function findThemeById(themeId: string): AppTheme {
  const direct = APP_THEMES.find((th) => th.id === themeId);
  if (direct) return direct;
  const legacyId = LEGACY_MAP[themeId];
  if (legacyId) {
    const mapped = APP_THEMES.find((th) => th.id === legacyId);
    if (mapped) return mapped;
  }
  return APP_THEMES[0]; // Fresh White default
}
